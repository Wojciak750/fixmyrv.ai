// Copies the server code into supabase/functions/qa-paperwork with Deno npm: imports.
// Run after any change to core/ or server/: npx tsx scripts/build-edge.ts
import { mkdirSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";

const ROOT = new URL("../", import.meta.url).pathname;
const OUT = ROOT + "supabase/functions/qa-paperwork/";
const PINS: Record<string, string> = {
  "pdf-lib": "npm:pdf-lib@1.17.1",
  fflate: "npm:fflate@0.8.3",
  "@anthropic-ai/sdk": "npm:@anthropic-ai/sdk@1.3.0",
  "@supabase/supabase-js": "npm:@supabase/supabase-js@2",
};
const SERVER = ["handler.ts", "types.ts", "sources.ts", "store-supabase.ts", "edge-entry.ts"];

function rewrite(src: string): string {
  return src.replace(/from "([^".][^"]*)"/g, (m, spec) => (PINS[spec] ? `from "${PINS[spec]}"` : m));
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT + "core", { recursive: true });
mkdirSync(OUT + "server", { recursive: true });
for (const f of readdirSync(ROOT + "core")) writeFileSync(OUT + "core/" + f, rewrite(readFileSync(ROOT + "core/" + f, "utf8")));
for (const f of SERVER) writeFileSync(OUT + "server/" + f, rewrite(readFileSync(ROOT + "server/" + f, "utf8")));
writeFileSync(OUT + "index.ts", `// Generated by agile-paperwork/scripts/build-edge.ts. Edit the source there, not here.\nimport "./server/edge-entry.ts";\n`);
const leftovers = readdirSync(OUT + "server").concat(readdirSync(OUT + "core")).flatMap((f) => {
  const dir = SERVER.includes(f) ? "server/" : "core/";
  return [...readFileSync(OUT + dir + f, "utf8").matchAll(/from "([^".][^"]*)"/g)].map((m) => m[1]).filter((s) => !s.startsWith("npm:"));
});
if (leftovers.length) throw new Error("Unpinned imports: " + leftovers.join(", "));
console.log("edge function written to", OUT);
